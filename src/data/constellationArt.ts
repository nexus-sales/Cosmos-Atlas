/**
 * Mythological constellation figure art — defined as polyline paths in
 * equatorial coordinates [RA_degrees, Dec_degrees].
 *
 * Each figure is composed of:
 *   paths — outline polylines (rendered as lines)
 *   fills — closed polygons (rendered as semi-transparent filled silhouettes)
 *
 * Coordinate conventions:
 *   RA  — right ascension in degrees [0, 360)
 *   Dec — declination in degrees [-90, +90]
 */

export type ArtPoint = [number, number]; // [ra_deg, dec_deg]
export type ArtPath = ArtPoint[];

export interface ConstellationFigure {
    /** Must match the key in CONSTELLATIONS data */
    name: string;
    paths: ArtPath[];
    /** Optional closed polygons for filled silhouette areas */
    fills?: ArtPath[];
}

